"""FIXED execution and accounting rules for the agent news-bot search (Nov 7 2026).

Every agent strategy MUST take its prices, posts, fills, exits and account figures from this module, so that all results
are on the same, realistic footing.  Do not edit this file (copy what you need into your own folder if you want a
faster variant, but its fills and exits must give the same results as these functions).

Data (`data_dir` argument; the agents get a copy that ends on 2026-06-30, the final check uses the full data):
  data_dir/ticks_exness*/<XAUUSDm|USTECm>/<YYYY-MM>.npz   1-second bars (UTC seconds `t`; bid/ask first/last/min/max; n)
  data_dir/telegram/history/**/financialjuice*.jsonl      FinancialJuice posts   (ch "FJ")
  data_dir/telegram/history/**/WalterBloomberg*.jsonl     Walter Bloomberg posts (ch "WB")
  data_dir/calendar/ff_calendar.csv                       economic calendar (time_utc, currency, impact, name, ...)

Rules (all enforced by the functions below):
  1. A post can be acted on no earlier than post time + LAT (2 s); stress test: + LAT_STRESS (5 s).
  2. Market buy fills at the ask of that second + 1 spread, sell at the bid - 1 spread (stress: 2 spreads).
     Stop orders fill at max(order price, ask of the trigger second) + 1 spread (buy; mirror for sell); the trigger is
     checked from the second AFTER the order is placed.  Limit orders fill at the order price only when the price trades
     at least 1 spread through it (stress: 2).  OCO pairs: if both trigger in the same second, take the WORSE leg.
  3. Every trade has a stop-loss distance fixed at entry, at least 3 spreads.  r = profit / stop distance (R).
  4. Exits are checked from the second after the fill.  Stop and target in the same second -> stop.  A price that gaps
     through the stop / target fills at that second's first price.  Timer exits fill at the first price of the first
     second at or after fill + max_hold.  Every position is closed at the last quote before a >= 10-minute pause
     (daily break, weekend).  Stress: 1 more spread lost on the exit.
  5. Account: risk 10 % of the balance at entry per trade (lot = 10 % x balance / (stop distance x contract)); P&L
     booked at exit; total open risk at most 30 % of the balance (a trade that would exceed it is skipped).
"""
from __future__ import annotations

import glob
import json
import os

import numpy as np
import pandas as pd

LAT, LAT_STRESS = 2, 5
GAP = 600
RISK, MAX_OPEN_RISK = 0.10, 0.30
SYMS = {"gold": "XAUUSDm", "nasdaq": "USTECm"}
CONTRACT = {"gold": 100.0, "nasdaq": 1.0}        # gold: 1 lot = 100 oz; Nasdaq: $1 per point per lot (check broker)
_TK: dict = {}
_POSTS: dict = {}
_GAPS: dict = {}


# ---------------------------------------------------------------- data
def load_ticks(inst: str, data_dir: str) -> dict:
    """All 1-second bars of gold / nasdaq in data_dir (2025 and 2026 folders), sorted by time."""
    key = (inst, os.path.abspath(data_dir))
    if key not in _TK:
        files = glob.glob(os.path.join(data_dir, "ticks_exness*", SYMS[inst], "*.npz"))
        files = sorted(files, key=os.path.basename)
        parts = [dict(np.load(f)) for f in files]
        tk = {k: np.concatenate([p[k] for p in parts]) for k in parts[0]}
        o = np.argsort(tk["t"], kind="stable")
        tk = {k: v[o] for k, v in tk.items()}
        keep = np.r_[True, np.diff(tk["t"]) > 0]
        _TK[key] = {k: v[keep] for k, v in tk.items()}
    return _TK[key]


def load_posts(data_dir: str) -> pd.DataFrame:
    """FinancialJuice + Walter Bloomberg posts: columns ts (int UTC seconds), t (Timestamp), ch, id, text."""
    key = os.path.abspath(data_dir)
    if key not in _POSTS:
        rows = []
        pat = os.path.join(data_dir, "telegram", "history", "**", "*.jsonl")
        for f in glob.glob(pat, recursive=True):
            b = os.path.basename(f)
            ch = "FJ" if b.startswith("financialjuice") else "WB" if b.startswith("WalterBloomberg") else None
            if ch is None:
                continue
            for line in open(f, encoding="utf-8"):
                try:
                    p = json.loads(line)
                except ValueError:
                    continue
                if p.get("time") and p.get("text"):
                    rows.append((p["time"], ch, int(p["id"]), p["text"]))
        df = pd.DataFrame(rows, columns=["time", "ch", "id", "text"]).drop_duplicates(["ch", "id"])
        df["t"] = pd.to_datetime(df.time, utc=True)
        df["ts"] = (df.t.astype("datetime64[ns, UTC]").astype("int64") // 10**9).astype(int)
        _POSTS[key] = df.drop(columns="time").sort_values(["ts", "ch", "id"]).reset_index(drop=True)
    return _POSTS[key]


def load_calendar(data_dir: str) -> pd.DataFrame:
    return pd.read_csv(os.path.join(data_dir, "calendar", "ff_calendar.csv"), parse_dates=["time_utc"])


# ---------------------------------------------------------------- helpers
def bar_at(tk: dict, ts: int):
    """index of the first second at / after ts (None if the next quote is more than 10 s later)."""
    i = int(np.searchsorted(tk["t"], ts))
    if i >= len(tk["t"]) or tk["t"][i] - ts > 10:
        return None
    return i


def next_close(tk: dict, i: int) -> int:
    """index of the last second before the next >= 10-minute pause in quotes at / after index i."""
    key = id(tk)
    if key not in _GAPS:
        _GAPS[key] = np.flatnonzero(np.diff(tk["t"]) >= GAP)
    g = _GAPS[key]
    k = np.searchsorted(g, i)
    return int(g[k]) if k < len(g) else len(tk["t"]) - 1


def spread(tk: dict, i: int) -> float:
    return float(tk["ask_first"][i] - tk["bid_first"][i])


# ---------------------------------------------------------------- entries
def market_entry(tk: dict, post_ts: int, d: int, delay: int = 0, stress: bool = False):
    """Market order in direction d (+1 buy / -1 sell) sent at post + LAT (+ delay seconds) -> (i, fill) or None."""
    i = bar_at(tk, post_ts + (LAT_STRESS if stress else LAT) + delay)
    if i is None:
        return None
    k = 2.0 if stress else 1.0
    af, bf = tk["ask_first"][i], tk["bid_first"][i]
    return i, float((af if d > 0 else bf) + d * k * (af - bf))


def pending_entry(tk: dict, i0: int, orders: list, expire_s: int, stress: bool = False):
    """Pending orders placed at second index i0, live until i0's time + expire_s (never past the next close).
    orders: list of (kind, d, price) with kind "stop" or "limit".  One cancels the others.
    -> (j, [(d, fill), ...]) for the first second any order triggers (2 legs if two trigger in that second: the
    caller must take the WORSE result), or None."""
    T = tk["t"]
    end = next_close(tk, i0)
    w = min(int(np.searchsorted(T, T[i0] + expire_s)), end + 1)
    a = i0 + 1
    if a >= w:
        return None
    k = 2.0 if stress else 1.0
    hits = []
    for kind, d, px in orders:
        if kind == "stop":
            h = (tk["ask_max"][a:w] >= px) if d > 0 else (tk["bid_min"][a:w] <= px)
        else:
            sp = tk["ask_first"][a:w] - tk["bid_first"][a:w]
            h = (tk["ask_min"][a:w] <= px - k * sp) if d > 0 else (tk["bid_max"][a:w] >= px + k * sp)
        hits.append(h)
    anyh = np.logical_or.reduce(hits)
    if not anyh.any():
        return None
    m = int(np.argmax(anyh))
    j = a + m
    af, bf = tk["ask_first"][j], tk["bid_first"][j]
    legs = []
    for (kind, d, px), h in zip(orders, hits):
        if h[m]:
            if kind == "stop":
                fill = (max(px, af) if d > 0 else min(px, bf)) + d * k * (af - bf)
            else:
                fill = px
            legs.append((d, float(fill)))
    return j, legs


# ---------------------------------------------------------------- exit
def exit_trade(tk: dict, j: int, fill: float, d: int, stop_dist: float, tp_r: float | None = None,
               max_hold_s: int | None = None, be_at_r: float | None = None, trail_r: float | None = None,
               stress: bool = False):
    """Position filled in second index j.  -> (exit index, r, stop distance used).
    stop_dist: price distance of the stop (raised to 3 spreads if smaller).  tp_r: target in R (None = no target).
    max_hold_s: timer exit (None = none).  be_at_r: once the price reaches +be_at_r R the stop moves to the entry.
    trail_r: once the price reaches +be_at_r R (or at once if be_at_r is None) the stop trails trail_r R behind the
    best price.  Stop changes apply from the next second.  Stress: 1 more spread lost."""
    T = tk["t"]
    sp0 = spread(tk, j)
    sd = max(float(stop_dist), 3 * sp0)
    end = next_close(tk, j)
    k_end = end + 1 if max_hold_s is None else min(int(np.searchsorted(T, T[j] + max_hold_s)), end + 1)
    timer = max_hold_s is not None and k_end <= end
    if d > 0:
        first, lo, hi, last = tk["bid_first"], tk["bid_min"], tk["bid_max"], tk["bid_last"]
    else:
        first, lo, hi, last = tk["ask_first"], tk["ask_max"], tk["ask_min"], tk["ask_last"]   # adverse = high for shorts
    sl = fill - d * sd
    tp = None if tp_r is None else fill + d * tp_r * sd
    a = j + 1
    out = None
    if be_at_r is None and trail_r is None:
        step = 1800
        while a < k_end and out is None:
            b = min(k_end, a + step)
            f, adv, fav = first[a:b], lo[a:b], hi[a:b]
            g_sl, h_sl = d * (f - sl) <= 0, d * (adv - sl) <= 0
            if tp is None:
                g_tp = h_tp = np.zeros(b - a, bool)
            else:
                g_tp, h_tp = d * (f - tp) >= 0, d * (fav - tp) >= 0
            hit = g_sl | h_sl | g_tp | h_tp
            if hit.any():
                m = int(np.argmax(hit))
                px = f[m] if (g_sl[m] or g_tp[m]) else (sl if h_sl[m] else tp)
                out = (a + m, px)
            a, step = b, step * 4
    else:
        best = fill
        armed = be_at_r is None
        for x in range(a, k_end):
            f, adv, fav = first[x], lo[x], hi[x]
            if d * (f - sl) <= 0:
                out = (x, f); break
            if tp is not None and d * (f - tp) >= 0:
                out = (x, f); break
            if d * (adv - sl) <= 0:
                out = (x, sl); break
            if tp is not None and d * (fav - tp) >= 0:
                out = (x, tp); break
            best = max(best, fav) if d > 0 else min(best, fav)
            if not armed and d * (best - fill) >= be_at_r * sd:
                armed = True
                sl = fill if d * (fill - sl) > 0 else sl
            if armed and trail_r is not None:
                cand = best - d * trail_r * sd
                if d * (cand - sl) > 0:
                    sl = cand
    if out is None:
        if timer:
            out = (k_end, first[k_end])
        else:
            k = min(end, len(T) - 1)
            out = (k, last[k])
    k, px = out
    r = d * (float(px) - fill) / sd
    if stress:
        r -= spread(tk, min(k, len(T) - 1)) / sd
    return int(k), float(r), sd


# ---------------------------------------------------------------- account
def account(trades: pd.DataFrame, risk: float = RISK, start: float = 1000.0, max_open_risk: float = MAX_OPEN_RISK) -> dict:
    """trades: columns entry_ts, exit_ts (int seconds), r; optional inst, sd (stop distance) for the lot size.
    Stake = risk x balance at entry, P&L = stake x r at exit, open risk <= max_open_risk x balance.
    -> final balance, max drawdown (of the balance after each exit), trades taken / skipped, biggest lot."""
    if len(trades) == 0:
        return dict(final=start, dd=0.0, taken=0, skipped=0, max_lot=0.0, wiped=False)
    tr = trades.sort_values(["entry_ts", "exit_ts"]).reset_index(drop=True)
    ev = [(int(x.exit_ts), 0, i) for i, x in tr.iterrows()] + [(int(x.entry_ts), 1, i) for i, x in tr.iterrows()]
    ev.sort()
    bal, peak, dd = start, start, 0.0
    open_st: dict = {}
    taken = skipped = 0
    max_lot = 0.0
    wiped = False
    for ts, kind, i in ev:
        if kind == 0:
            if i in open_st:
                bal += open_st.pop(i) * tr.r[i]
                if bal <= 0.01:
                    bal, wiped = 0.0, True
                peak = max(peak, bal)
                dd = min(dd, bal / peak - 1)
        else:
            if wiped:
                skipped += 1
                continue
            st = risk * bal
            if sum(open_st.values()) + st > max_open_risk * bal + 1e-9:
                skipped += 1
                continue
            open_st[i] = st
            taken += 1
            if "sd" in tr and "inst" in tr:
                max_lot = max(max_lot, st / (tr.sd[i] * CONTRACT[tr.inst[i]]))
    return dict(final=bal, dd=dd, taken=taken, skipped=skipped, max_lot=max_lot, wiped=wiped)


def metrics(trades: pd.DataFrame, start: str, end: str, risk: float = RISK) -> dict:
    """Trades whose entry is in [start, end): count, R, PF, win rate, and the account at `risk`."""
    a, b = pd.Timestamp(start, tz="UTC").timestamp(), pd.Timestamp(end, tz="UTC").timestamp()
    t = trades[(trades.entry_ts >= a) & (trades.entry_ts < b)] if len(trades) else trades
    r = t.r.to_numpy(float) if len(t) else np.zeros(0)
    gw, gl = r[r > 0].sum(), -r[r < 0].sum()
    acc = account(t, risk) if len(t) else account(pd.DataFrame(columns=["entry_ts", "exit_ts", "r"]), risk)
    return dict(n=len(r), R=float(r.sum()), pf=float(gw / gl) if gl > 0 else (99.0 if gw > 0 else 0.0),
                win=float((r > 0).mean()) if len(r) else 0.0, **acc)
